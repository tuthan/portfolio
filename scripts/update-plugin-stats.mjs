#!/usr/bin/env node
/**
 * Refreshes the Omarchy marketplace engagement snapshot in src/data/pluginStats.ts.
 *
 * Reads the same public, read-only endpoint the marketplace page itself calls.
 * Records nothing: it never posts view, copy or heart events.
 *
 * Run manually with `npm run stats`, or as a best-effort step before a deploy
 * build. On any failure it leaves the committed snapshot untouched and exits 0
 * so a network hiccup can never break the build.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const STATS_URL = 'https://api.omarchyplugins.com/v1/stats'
const TIMEOUT_MS = 15_000

/** Plugin ids to track, in the order they should appear, with their display names. */
const TRACKED = [
  ['io.github.tuthan.dropdown-terminal', 'Dropdown Terminal'],
  ['io.github.hvo.omarchy-unraid', 'Unraid Monitor'],
  ['io.github.tuthan.omasafe', 'OmaSafe bar plugin'],
  ['io.github.tuthan.omarchy-lunar-calendar', 'Lunar Calendar'],
]

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(root, 'src/data/pluginStats.ts')
const LLMS = resolve(root, 'public/llms.txt')
const LLMS_START = '<!-- plugin-stats:start -->'
const LLMS_END = '<!-- plugin-stats:end -->'

function bail(reason) {
  console.warn(`[plugin-stats] keeping committed snapshot: ${reason}`)
  process.exit(0)
}

function render(entries, updatedAt) {
  const rows = entries
    .map(([id, s]) => `  '${id}': { views: ${s.views}, copies: ${s.copies}, hearts: ${s.hearts} },`)
    .join('\n')
  return `// Generated by scripts/update-plugin-stats.mjs — do not edit by hand.
// Source: ${STATS_URL} (public read-only engagement stats).

export interface PluginStats {
  /** Plugin detail page views on plugins.omarchy.org. */
  views: number
  /** Times the install command was copied. */
  copies: number
  /** Hearts given on the marketplace listing. */
  hearts: number
}

/** ISO date the snapshot below was taken. */
export const pluginStatsUpdatedAt = '${updatedAt}'

export const pluginStats: Record<string, PluginStats> = {
${rows}
}
`
}

const controller = new AbortController()
const timer = setTimeout(() => controller.abort(), TIMEOUT_MS)

let payload
try {
  const res = await fetch(STATS_URL, {
    signal: controller.signal,
    headers: { Accept: 'application/json' },
  })
  if (!res.ok) bail(`HTTP ${res.status}`)
  payload = await res.json()
} catch (err) {
  bail(err instanceof Error ? err.message : String(err))
} finally {
  clearTimeout(timer)
}

const plugins = payload?.plugins
if (!plugins || typeof plugins !== 'object') bail('unexpected response shape')

const entries = []
for (const [id, name] of TRACKED) {
  const raw = plugins[id]
  if (!raw) {
    console.warn(`[plugin-stats] ${id} missing from the response, skipping`)
    continue
  }
  const views = Number(raw.views) || 0
  const copies = Number(raw.copies) || 0
  const hearts = Number(raw.hearts) || 0
  entries.push([id, { views, copies, hearts, name }])
}

if (entries.length === 0) bail('no tracked plugins found in the response')

const updatedAt = new Date().toISOString().slice(0, 10)
await writeFile(OUT, render(entries, updatedAt), 'utf8')

// Keep the agent-facing summary in llms.txt in step with the site.
try {
  const current = await readFile(LLMS, 'utf8')
  const from = current.indexOf(LLMS_START)
  const to = current.indexOf(LLMS_END)
  if (from === -1 || to === -1 || to < from) {
    console.warn('[plugin-stats] llms.txt markers not found, leaving it unchanged')
  } else {
    const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`
    const lines = entries
      .map(
        ([, s]) =>
          `- **${s.name}**: ${plural(s.views, 'view', 'views')}, ` +
          `${plural(s.copies, 'install-command copy', 'install-command copies')}, ` +
          `${plural(s.hearts, 'heart', 'hearts')}.`,
      )
      .join('\n')
    const block = `${LLMS_START}\nMarketplace engagement on plugins.omarchy.org, as of ${updatedAt}:\n\n${lines}\n${LLMS_END}`
    await writeFile(LLMS, current.slice(0, from) + block + current.slice(to + LLMS_END.length), 'utf8')
  }
} catch (err) {
  console.warn(`[plugin-stats] could not update llms.txt: ${err instanceof Error ? err.message : String(err)}`)
}

const total = entries.reduce((n, [, s]) => n + s.views, 0)
console.log(`[plugin-stats] wrote ${entries.length} plugins (${total} total views) as of ${updatedAt}`)
for (const [id, s] of entries) {
  console.log(`  ${id.padEnd(42)} views=${s.views} copies=${s.copies} hearts=${s.hearts}`)
}
